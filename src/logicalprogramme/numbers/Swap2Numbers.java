package logicalprogramme.numbers;

public class
Swap2Numbers {
    public static void main(String[] args) {

       int a=50;
       int b=91;
        System.out.println("Numbers before swappings are ");
        System.out.println("a="+a + " and b=" + b);
        System.out.println("Numbers after swappings are ");

        int c;
        c=a;
        a=b;
        b=c;
        System.out.println("a=" + a + " and b= " + b);
    }

}
