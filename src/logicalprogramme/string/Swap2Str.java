package logicalprogramme.string;

public class Swap2Str {
    public static void main(String[] args) {
        String s1="SACHIN";
        String s2="SHLOK";
        String temp;
        temp=s1;
        s1=s2;
        s2=temp;

        System.out.println(s1);
        System.out.println(s2);

    }
}
